HERE = Path(__file__).resolve().parent
NONCE = "0123456789abcdef0123456789abcdef"
CAPABILITY = "fedcba9876543210fedcba9876543210"


class Fixture:
    def __init__(self, name, timeout=8, *, paired_block=None, history_growth_guard=False):
        # Retain each fixture's generated bytes and failure/cleanup evidence.
        self.temporary_output = None
        output_root = os.environ.get("RESIZE_PTY_TEST_OUTPUT")
        if output_root is None:
            self.temporary_output = tempfile.TemporaryDirectory(prefix="cmdy-resize-pty-tests-")
            output_root = self.temporary_output.name
        root = Path(output_root)
        root.mkdir(parents=True, exist_ok=True)
        self.output = root / name
        self.socket_directory = tempfile.TemporaryDirectory(prefix="resize-unit-", dir="/private/tmp")
        self.export_directory = None
        extra = []
        child_options = {}
        if paired_block is not None:
            self.export_directory = tempfile.TemporaryDirectory(prefix="resize-export-unit-", dir="/private/tmp")
            extra = ["--paired-block", str(paired_block), "--calibration-nonce", NONCE[::-1],
                     "--export-directory", self.export_directory.name]
            if history_growth_guard: extra.append("--history-growth-guard")
            child_options = dict(env=dict(os.environ, TMPDIR=self.export_directory.name + "/"), umask=0o077)
        self.received_limit = 16 * 1024 * 1024 if paired_block is not None else 4 * 1024 * 1024
        self.master, slave = pty.openpty()
        self.saved = termios.tcgetattr(slave)
        fcntl.ioctl(self.master, termios.TIOCSWINSZ, struct.pack("HHHH", 36, 120, 0, 0))

        def own_terminal():
            os.setsid()
            fcntl.ioctl(0, termios.TIOCSCTTY, 0)
            os.tcsetpgrp(0, os.getpgrp())

        self.process = subprocess.Popen([sys.executable, "-B", str(HERE / "resize_worker.py"),
            "--output", str(self.output), "--socket-directory", self.socket_directory.name,
            "--capability", CAPABILITY, "--nonce", NONCE, "--timeout", str(timeout), *extra],
            stdin=slave, stdout=slave, stderr=slave, preexec_fn=own_terminal,
            close_fds=True, cwd=HERE, **child_options)
        os.close(slave)
        self.received = bytearray()
        self.disconnected = False
        self.reader = threading.Thread(target=self.drain, daemon=True)
        self.reader.start()
        self.ready = self.await_json("ready.json")
        if self.ready["pid"] != self.process.pid or self.ready["parentPID"] != os.getpid():
            raise AssertionError("fixture process identity does not match owned subprocess")

    def drain(self):
        while not self.disconnected:
            try:
                if not select.select([self.master], [], [], 0.025)[0]:
                    if self.process.poll() is not None:
                        break
                    continue
                chunk = os.read(self.master, 65536)
                if not chunk:
                    break
                self.received.extend(chunk)
                if len(self.received) > self.received_limit:
                    break
            except (OSError, ValueError):
                break

    def await_json(self, name, seconds=3):
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            path = self.output / name
            if path.is_file():
                return json.loads(path.read_text())
            if self.process.poll() is not None:
                raise AssertionError(f"worker exited {self.process.returncode} before {name}: {bytes(self.received[-2000:])!r}")
            time.sleep(0.01)
        raise AssertionError("fixture did not publish " + name)

    def request(self, operation, **fields):
        return worker_request(self.ready, CAPABILITY, operation, **fields)

    def completed(self, count):
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline:
            status = self.request("status")
            if status["completedEvents"] == count:
                return status
            time.sleep(0.015)
        raise AssertionError("resize event did not complete")

    def resize(self, columns, rows):
        # Test harness alone mutates its private PTY. The production controller
        # has no TIOCSWINSZ/stty path; its app must update PTY geometry via AX.
        fcntl.ioctl(self.master, termios.TIOCSWINSZ, struct.pack("HHHH", rows, columns, 0, 0))

    def signal(self, value):
        if self.process.poll() is not None:
            raise AssertionError("owned fixture already exited")
        os.kill(self.process.pid, value)

    def wait(self):
        self.process.wait(timeout=4)
        self.reader.join(timeout=1)
        cleanup = json.loads((self.output / "cleanup.json").read_text())
        if not cleanup.get("signalWakeupRestored") or not cleanup.get("signalPipeClosed"):
            raise AssertionError("owned signal wakeup pipe was not exactly restored/closed")
        if not self.disconnected and cleanup.get("termiosRestored"):
            if termios.tcgetattr(self.master) != self.saved:
                raise AssertionError("claimed restored termios differs from original")
        return cleanup

    def close(self):
        if self.process.poll() is None:
            self.signal(signal.SIGTERM)
        try:
            self.process.wait(timeout=4)
        finally:
            if not self.disconnected:
                self.disconnected = True
                os.close(self.master)
            self.reader.join(timeout=1)
            self.socket_directory.cleanup()
            if self.export_directory is not None: self.export_directory.cleanup()
            if self.temporary_output is not None: self.temporary_output.cleanup()


@unittest.skipUnless(sys.platform == "darwin", "the private worker records Darwin mach ticks")
class ResizeWorkerTests(unittest.TestCase):
    def fixture(self, timeout=8):
        result = Fixture(self._testMethodName, timeout)
        self.addCleanup(result.close)
        return result

    def test_two_real_resizes_have_exact_order_bytes_and_one_signal_credit(self):
        worker = self.fixture()
        initial = worker.request("prepare")
        self.assertEqual(initial["history"]["payloadSHA256"], digest(history(NONCE)))
        self.assertEqual(initial["history"]["completedBytes"], 147000)
        self.assertEqual(initial["completedEvents"], 0)
        arm = worker.request("arm", sequence=1, grid=dict(columns=132, rows=40))
        self.assertEqual(arm["completedEvents"], 0)
        worker.signal(signal.SIGWINCH)  # Signal alone cannot authorize target.
        time.sleep(0.04)
        unchanged = worker.request("status")
        self.assertEqual(unchanged["completedEvents"], 0)
        self.assertIsNotNone(unchanged["pending"])
        worker.resize(132, 40)
        first = worker.completed(1)
        self.assertIsNone(first["pending"])
        worker.signal(signal.SIGWINCH)  # Duplicate unchanged geometry is inert.
        time.sleep(0.04)
        self.assertEqual(worker.request("status")["completedEvents"], 1)
        worker.request("arm", sequence=2, grid=dict(columns=120, rows=36))
        worker.resize(120, 36)
        events = worker.completed(2)["events"]
        self.assertEqual([event["sequence"] for event in events], [1, 2])
        for event, (columns, rows) in zip(events, [(132, 40), (120, 36)]):
            payload = frame_bytes(NONCE, event["sequence"], columns, rows)
            self.assertEqual(event["offeredBytes"], len(payload))
            self.assertEqual(event["completedBytes"], len(payload))
            self.assertEqual(event["payloadSHA256"], digest(payload))
            self.assertGreater(event["signalCounter"], event["armSignalCounter"])
            self.assertLessEqual(event["armedTicks"], event["signalReceivedTicks"])
            self.assertLessEqual(event["signalReceivedTicks"], event["observedTicks"])
            self.assertLessEqual(event["observedTicks"], event["startedTicks"])
            self.assertLessEqual(event["startedTicks"], event["completedTicks"])
        worker.request("finish")
        cleanup = worker.wait()
        self.assertEqual(worker.process.returncode, 0)
        self.assertEqual(cleanup["error"], "")
        self.assertTrue(cleanup["termiosRestored"])
        self.assertGreater(cleanup["signalWakeupBytesRead"], 0)
        receipts = json.loads((worker.output / "received.json").read_text())
        self.assertEqual(receipts["events"], events)

    def test_unsolicited_resize_after_prepare_is_invalid(self):
        worker = self.fixture()
        worker.request("prepare")
        worker.resize(132, 40)
        cleanup = worker.wait()
        self.assertNotEqual(worker.process.returncode, 0)
        self.assertIn("unsolicited resize", cleanup["error"])
        self.assertTrue(cleanup["termiosRestored"])

    def test_wrong_capability_fails_closed_and_preserves_cleanup(self):
        worker = self.fixture()
        with self.assertRaises(RuntimeError):
            worker_request(worker.ready, "0" * 32, "prepare")
        cleanup = worker.wait()
        self.assertNotEqual(worker.process.returncode, 0)
        self.assertIn("capability", cleanup["error"])
        self.assertTrue(cleanup["termiosRestored"])
        self.assertEqual(json.loads((worker.output / "received.json").read_text())["events"], [])

    def test_timeout_retains_armed_but_unpainted_event(self):
        worker = self.fixture(timeout=1.5)
        worker.request("prepare")
        worker.request("arm", sequence=1, grid=dict(columns=132, rows=40))
        cleanup = worker.wait()
        self.assertEqual(cleanup["stopReason"], "timeout")
        self.assertEqual(cleanup["pending"]["sequence"], 1)
        self.assertEqual(cleanup["uncompletedOfferedSequence"], 1)
        self.assertTrue(cleanup["termiosRestored"])
        self.assertEqual(json.loads((worker.output / "received.json").read_text())["events"], [])

    def test_sigterm_restores_and_retains_cleanup(self):
        worker = self.fixture()
        worker.request("prepare")
        worker.signal(signal.SIGTERM)
        cleanup = worker.wait()
        self.assertEqual(cleanup["stopReason"], "SIGTERM")
        self.assertTrue(cleanup["termiosRestored"])

    def test_sighup_restores_and_retains_cleanup(self):
        worker = self.fixture()
        worker.signal(signal.SIGHUP)
        cleanup = worker.wait()
        self.assertEqual(cleanup["stopReason"], "SIGHUP")
        self.assertTrue(cleanup["termiosRestored"])

    def test_disconnected_pty_retains_failure_evidence_and_exits(self):
        worker = self.fixture()
        worker.disconnected = True
        worker.reader.join(timeout=1)
        os.close(worker.master)
        cleanup = worker.wait()
        self.assertNotEqual(worker.process.returncode, 0)
        self.assertIn(cleanup["stopReason"], ("SIGHUP", "PTY-EOF", "error"))
        self.assertIn("termiosRestored", cleanup)
        self.assertTrue((worker.output / "received.json").is_file())


if __name__ == "__main__":
    unittest.main()
