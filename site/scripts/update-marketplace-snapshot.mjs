import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const registryPath = resolve(
  here,
  process.argv[2] ?? "../../../cmdy-registry/registry.json"
);
const outputPath = resolve(here, "../public/marketplace-data.js");
const source = await readFile(registryPath);
const registry = JSON.parse(source.toString("utf8"));

if (!registry || !Array.isArray(registry.entries) || !Array.isArray(registry.featured)) {
  throw new Error(`${registryPath} is not a cmdy registry`);
}

const serializedRegistry = JSON.stringify(registry);
if (serializedRegistry.includes("github.com/suprb/termite-registry")
    || serializedRegistry.includes("github.com/suprb/term64-registry")) {
  throw new Error(`${registryPath} still contains legacy public repository URLs`);
}
if (registry.name !== "the cmdy marketplace") {
  throw new Error(`${registryPath} has the wrong public marketplace name`);
}

const digest = createHash("sha256").update(source).digest("hex");
const header = `/* Bundled fallback for the static Marketplace page.
   Source: https://github.com/suprb/cmdy-registry
   Registry sha256: ${digest}
   Generated by: npm run snapshot
   Refresh this snapshot when the public registry changes. */\n`;
const output = `${header}window.CMDY_MARKETPLACE_SNAPSHOT = ${JSON.stringify(registry, null, 2)};\n`;

await writeFile(outputPath, output);
console.log(`wrote ${registry.entries.length} packages to ${outputPath}`);
