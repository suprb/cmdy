#!/usr/bin/env python3
"""Generate native cell-text segmentation data from authenticated Unicode 16 files.

This is the Swift 6.2/macOS 26 compatibility data, independent of CMDY's
Unicode 17 terminal-width policy. No generated table is loaded at runtime.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import struct

VERSION = '16.0.0'
SOURCES = {
    'ucd/auxiliary/GraphemeBreakProperty.txt': 'c29360bd6f7132811d701d29069541e827eb44bfc4c8fbde8c370d6982689dc1',
    'ucd/DerivedCoreProperties.txt': '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
    'ucd/emoji/emoji-data.txt': 'f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a',
    'ucd/auxiliary/GraphemeBreakTest.txt': 'ee2b9354d270ac061b29f09662cafea06341d77e704b8cc6bd72aaeeda363cb5',
}
CLASSES = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
           'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']

def inputs(cache):
    result = {}
    for name, expected in SOURCES.items():
        path = cache / name
        if not path.exists():
            data = subprocess.check_output(['curl', '--fail', '--silent', '--show-error',
                '--location', f'https://www.unicode.org/Public/{VERSION}/{name}'])
            if hashlib.sha256(data).hexdigest() != expected:
                raise ValueError(f'Unauthenticated Unicode input: {name}')
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f'Unicode input hash changed: {name}')
        result[name] = data.decode('utf-8')
    return result

def records(text):
    for line in text.splitlines():
        fields = [v.strip() for v in line.split('#', 1)[0].split(';')]
        if not fields[0]:
            continue
        bounds = fields[0].split('..')
        lo, hi = int(bounds[0], 16), int(bounds[-1], 16)
        yield lo, hi, fields[1:]

def generate(source):
    data = bytearray(0x110000)
    for lo, hi, fields in records(source['ucd/auxiliary/GraphemeBreakProperty.txt']):
        value = CLASSES.index(fields[0])
        data[lo:hi+1] = bytes([value]) * (hi-lo+1)
    for lo, hi, fields in records(source['ucd/emoji/emoji-data.txt']):
        if fields[0] == 'Extended_Pictographic':
            for i in range(lo, hi+1): data[i] |= 0x10
    for lo, hi, fields in records(source['ucd/DerivedCoreProperties.txt']):
        if fields[0] == 'InCB':
            value = ['None', 'Consonant', 'Extend', 'Linker'].index(fields[1]) << 5
            for i in range(lo, hi+1): data[i] |= value
    # Modern Hangul syllables alternate LV/LVT in 28-scalar blocks. Express that
    # rule arithmetically rather than retaining 798 generated table intervals.
    assert all(data[i] == (12 if (i - 0xac00) % 28 == 0 else 13)
               for i in range(0xac00, 0xd7a4))
    data[0xac00:0xd7a4] = bytes(0xd7a4 - 0xac00)
    lines = ['// Generated by Core/Tools/ZigEngine/Grapheme/generate.py; do not edit.',
             '// Unicode 16.0.0 UAX #29 properties for the frozen Swift text contract.',
             '// Unicode data license: https://www.unicode.org/license.txt']
    lines += [f'// {name} SHA-256 {sha}' for name, sha in SOURCES.items()]
    lines += ['const Range = struct { first: u32, last: u32, value: u8 };',
              'const ranges = [_]Range{']
    start = 0
    for i in range(1, len(data)+1):
        if i == len(data) or data[i] != data[start]:
            if data[start]: lines.append(f'    .{{ .first = 0x{start:x}, .last = 0x{i-1:x}, .value = {data[start]} }},')
            start = i
    lines += ['};', '', 'pub fn property(scalar: u32) u8 {',
              '    if (scalar >= 0xac00 and scalar <= 0xd7a3)',
              '        return if ((scalar - 0xac00) % 28 == 0) 12 else 13;',
              '    var low: usize = 0;', '    var high: usize = ranges.len;',
              '    while (low < high) {', '        const middle = low + (high - low) / 2;',
              '        const range = ranges[middle];',
              '        if (scalar < range.first) high = middle else if (scalar > range.last) low = middle + 1 else return range.value;',
              '    }', '    return 0;', '}', '']
    return '\n'.join(lines)

def test_data(source):
    result = bytearray()
    for raw in source['ucd/auxiliary/GraphemeBreakTest.txt'].splitlines():
        fields = raw.split('#', 1)[0].split()
        if not fields: continue
        scalars = [int(v, 16) for v in fields if v not in ('÷', '×')]
        boundaries = [v for v in fields if v in ('÷', '×')]
        assert len(scalars) <= 7 and len(boundaries) == len(scalars)+1
        mask = sum((value == '÷') << i for i, value in enumerate(boundaries))
        result += bytes([len(scalars), mask])
        result += struct.pack('<'+'I'*len(scalars), *scalars)
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[3] / 'Zig/grapheme_properties.zig')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = inputs(args.cache)
    output = generate(source)
    fixture = test_data(source)
    fixture_path = args.output.parent / 'testdata/grapheme_break_tests.bin'
    if args.check:
        if args.output.read_text() != output: raise SystemExit('Generated grapheme data differs')
        if fixture_path.read_bytes() != fixture: raise SystemExit('Generated grapheme tests differ')
    else:
        args.output.write_text(output)
        fixture_path.parent.mkdir(parents=True, exist_ok=True)
        fixture_path.write_bytes(fixture)
    print(hashlib.sha256(output.encode()).hexdigest())
