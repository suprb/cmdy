#!/usr/bin/env python3
"""Translate CMDY's pinned width data verbatim for the production Zig engine."""
import argparse
import hashlib
import tempfile
from pathlib import Path
import re


def generate(source, output):
    text = source.read_text()
    definitions = []
    for swift, zig, typ, expected in [('widthPageIndices', 'pages', 'u8', 4352),
                                     ('widthPageWords', 'words', 'u64', 848)]:
        body = re.search(r'static let ' + swift + r': \[UInt\d+\] = \[(.*?)\n    \]', text, re.S)[1]
        values = re.findall(r'0x[0-9A-Fa-f]+|\d+', body)
        assert len(values) == expected
        lines = ['    ' + ', '.join(values[i:i+16]) + ',' for i in range(0, len(values), 16)]
        definitions.append('const ' + zig + ' = [_]' + typ + '{\n' + '\n'.join(lines) + '\n};')
    regions = re.search(r'static let regionalIndicators:.*?\[(.*?)\n    \]', text, re.S)[1]
    assert re.findall(r'\.init\((0x\w+), (0x\w+)\)', regions) == [('0x01F1E6', '0x01F1FF')]
    body = re.search(r'static let emojiVS16Bases:.*?\[(.*?)\n    \]', text, re.S)[1]
    ranges = re.findall(r'\.init\((0x\w+), (0x\w+)\)', body)
    assert ranges
    flags = bytearray(0x110000)
    for start, end in ranges:
        start, end = int(start, 16), int(end, 16)
        assert 0 <= start <= end < len(flags)
        flags[start:end + 1] = bytes([1]) * (end - start + 1)
    unique, indices, packed = {}, [], []
    for start in range(0, len(flags), 256):
        page = bytes(flags[start:start + 256])
        if page not in unique:
            unique[page] = len(unique)
            for word in range(4):
                packed.append(sum(page[word * 64 + bit] << bit for bit in range(64)))
        indices.append(unique[page])
    assert len(unique) <= 256 and len(indices) == 4352
    for name, values, typ in [('vs16_pages', indices, 'u8'), ('vs16_words', packed, 'u64')]:
        lines = ['    ' + ', '.join(map(str, values[i:i+16])) + ',' for i in range(0, len(values), 16)]
        definitions.append('const ' + name + ' = [_]' + typ + '{\n' + '\n'.join(lines) + '\n};')
    output.write_text('// Generated from CMDY UnicodeWidthTables.swift; do not hand edit.\n'
        '// Source SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n' +
        '\n'.join(definitions) + '''
pub fn width(scalar: u32) i8 {
    if (scalar > 0x10ffff or (scalar >= 0xd800 and scalar <= 0xdfff)) return -1;
    const page: usize = pages[scalar >> 8];
    const shift: u6 = @intCast((scalar & 31) * 2);
    return @as(i8, @intCast((words[page * 8 + ((scalar >> 5) & 7)] >> shift) & 3)) - 1;
}
pub fn ordinaryWidth(scalar: u32) i8 {
    if (scalar == 0x200d or scalar == 0xfe0e or scalar == 0xfe0f or
        (scalar >= 0xe0100 and scalar <= 0xe01ef) or
        (scalar >= 0x1f1e6 and scalar <= 0x1f1ff)) return 0;
    return width(scalar);
}
pub fn isVS16Base(scalar: u32) bool {
    if (scalar > 0x10ffff or (scalar >= 0xd800 and scalar <= 0xdfff)) return false;
    const page: usize = vs16_pages[scalar >> 8];
    const shift: u6 = @intCast(scalar & 63);
    return ((vs16_words[page * 4 + ((scalar >> 6) & 3)] >> shift) & 1) != 0;
}
''')


def generated_extras(source):
    text = source.read_text()
    body = re.search(r'static let ambiguous:.*?\[(.*?)\n    \]', text, re.S)[1]
    ranges = re.findall(r'\.init\((0x\w+), (0x\w+)\)', body)
    if len(ranges) != 179:
        raise ValueError("Pinned Unicode 17 ambiguous ranges changed")
    properties = '// Unicode 17 ambiguous property from CMDY generated tables.\n'
    properties += '// Source SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    properties += 'const ranges = [_][2]u32{\n'
    properties += ''.join('    .{ ' + lower + ', ' + upper + ' },\n' for lower, upper in ranges)
    properties += """};
pub fn isAmbiguous(scalar: u32) bool {
    var low: usize = 0;
    var high: usize = ranges.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const range = ranges[middle];
        if (scalar < range[0]) high = middle else if (scalar > range[1]) low = middle + 1 else return true;
    }
    return false;
}
"""
    metadata = text[:text.index('    // 4352 page indices')].rstrip() + '\n}\n'
    metadata = metadata.replace('Generated by Core/Tools/UnicodeWidth/generate.py.',
                                'Generated by Core/Tools/ZigEngine/generate-unicode.py.')
    return properties, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    core = Path(__file__).resolve().parents[2]
    source = core / 'Sources/CmdyCore/Generated/UnicodeWidthTables.swift'
    # The upstream UnicodeWidth generator authenticates the published Unicode
    # inputs. This deterministic translation preserves its exact checked bytes.
    with tempfile.TemporaryDirectory(prefix='cmdy-native-unicode-') as work:
        output = Path(work) / 'unicode.zig'
        generate(source, output)
        properties, metadata = generated_extras(source)
        generated = {
            core / 'Zig/unicode.zig': output.read_text(),
            core / 'Zig/unicode_properties.zig': properties,
            core / 'Sources/CmdyCoreZig/UnicodeMetadata.swift': metadata,
        }
        for path, content in generated.items():
            if args.check:
                if path.read_text() != content:
                    raise SystemExit('Native Unicode output differs: ' + str(path))
                print('Verified: ' + str(path))
            else:
                path.write_text(content)
                print('Generated: ' + str(path))


if __name__ == '__main__':
    main()
